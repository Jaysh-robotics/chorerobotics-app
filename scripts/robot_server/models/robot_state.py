"""
Robot state machine and connection state models.

The RobotState class is the central state manager for the robot server.
It tracks the current operational state (idle, working, estop, etc.),
active task progress, connection status, and pairing state.

All modules read from and write to a shared RobotState instance.
Thread safety is ensured via asyncio (single-threaded event loop).
"""

from dataclasses import dataclass, field
from typing import Optional, Dict, Any, List
from enum import Enum
import time


class OperationalState(Enum):
    """Robot operational state machine states."""

    IDLE = "idle"
    WORKING = "working"
    CHARGING = "charging"
    PAUSED = "paused"
    ERROR = "error"
    ESTOP = "estop"
    DOCKED = "docked"


class PairingPhase(Enum):
    """BLE pairing state machine phases.

    These map to the LED states defined in led_pairing_spec.md.
    """

    DISCOVERABLE = 0  # White slow blink
    FOUND = 1  # White fast blink
    PAIRING = 2  # White double blink
    AWAITING_CODE = 3  # White solid
    VERIFYING = 4  # White rapid blink
    SUCCESS = 5  # Green 3 flashes then solid
    WIFI_SETUP = 6  # Green slow blink
    COMPLETE = 7  # Green solid
    FAILED = 8  # Red 3 flashes


class ConnectionType(Enum):
    """Type of connection from an app client."""

    BLE = "ble"
    WEBSOCKET = "websocket"
    CLOUD = "cloud"


@dataclass
class PairingState:
    """Tracks the current BLE pairing state machine.

    The pairing state machine controls:
    1. LED visual feedback (via LedController)
    2. BLE GATT characteristic values (PairingState, PairingResult)
    3. Whether the robot accepts connections

    Lifecycle:
        DISCOVERABLE -> FOUND -> PAIRING -> AWAITING_CODE -> VERIFYING
        -> SUCCESS -> WIFI_SETUP -> COMPLETE
        or
        -> FAILED -> DISCOVERABLE (after 3 seconds)
    """

    phase: PairingPhase = PairingPhase.DISCOVERABLE
    """Current pairing phase."""

    is_paired: bool = False
    """Whether the robot has been successfully paired with an app instance."""

    pairing_code: Optional[str] = None
    """6-digit pairing code generated by the robot. None before generation."""

    pairing_token: Optional[str] = None
    """32-char hex token generated after successful pairing. Used for WebSocket auth."""

    connected_device_address: Optional[str] = None
    """BLE MAC address of the connected app device."""

    pairing_started_at: Optional[float] = None
    """Unix timestamp when pairing process started (for timeout)."""

    def is_timed_out(self) -> bool:
        """Check if the pairing process has exceeded the 2-minute timeout.

        Returns:
            True if more than 120 seconds have elapsed since pairing started.
        """
        from ..config import BLE_PAIRING_TIMEOUT_S

        if self.pairing_started_at is None:
            return False
        return (time.time() - self.pairing_started_at) > BLE_PAIRING_TIMEOUT_S

    def reset(self) -> None:
        """Reset to initial discoverable state.

        Called after timeout, pairing failure, or manual reset.
        Does NOT clear is_paired or pairing_token (those survive resets).
        """
        self.phase = PairingPhase.DISCOVERABLE
        self.pairing_code = None
        self.connected_device_address = None
        self.pairing_started_at = None


@dataclass
class ConnectionState:
    """Tracks all active connections from app clients.

    The robot can have simultaneous connections from multiple channels:
    - One BLE connection (max 1 paired device)
    - Multiple WebSocket connections (max 3)
    - Firebase cloud (always-on when internet available)
    """

    ble_connected: bool = False
    """Whether a BLE GATT client is currently connected."""

    ble_device_address: Optional[str] = None
    """BLE MAC address of connected device."""

    websocket_clients: int = 0
    """Number of active WebSocket connections."""

    cloud_connected: bool = False
    """Whether Firebase cloud connectivity is available."""

    last_ble_activity_ms: int = 0
    """Unix ms of last BLE read/write/notify."""

    last_websocket_activity_ms: int = 0
    """Unix ms of last WebSocket message received."""

    last_cloud_activity_ms: int = 0
    """Unix ms of last Firebase interaction."""

    def has_any_connection(self) -> bool:
        """Check if any communication channel is active."""
        return self.ble_connected or self.websocket_clients > 0 or self.cloud_connected

    def has_local_connection(self) -> bool:
        """Check if any local (low-latency) connection is active.

        Local connections (BLE, WiFi) are required for safety-critical
        operations like manual control and blade toggle.
        """
        return self.ble_connected or self.websocket_clients > 0

    def best_channel(self) -> Optional[ConnectionType]:
        """Return the best available communication channel.

        Priority: BLE > WebSocket > Cloud
        BLE is preferred for lowest latency.

        Returns:
            The best ConnectionType, or None if disconnected.
        """
        if self.ble_connected:
            return ConnectionType.BLE
        if self.websocket_clients > 0:
            return ConnectionType.WEBSOCKET
        if self.cloud_connected:
            return ConnectionType.CLOUD
        return None

    def seconds_since_any_activity(self) -> float:
        """Seconds elapsed since any communication channel was active.

        Used by the connection loss safety handler to determine
        whether to pause, dock, or E-Stop.
        """
        latest = max(
            self.last_ble_activity_ms,
            self.last_websocket_activity_ms,
            self.last_cloud_activity_ms,
        )
        if latest == 0:
            return float("inf")
        return (time.time() * 1000 - latest) / 1000.0


@dataclass
class TaskState:
    """Tracks the state of the currently active autonomous task.

    This mirrors the ActiveTaskState in the Flutter app's active_task_bloc.dart.
    All task progress updates originate from the ROS2 /task/progress topic.
    """

    task_id: Optional[str] = None
    """Unique task ID, assigned when task starts."""

    task_type: Optional[str] = None
    """Task type: 'mow', 'plow', 'collect'."""

    zone_id: Optional[str] = None
    """ID of the zone being operated on."""

    zone_name: Optional[str] = None
    """Human-readable zone name (denormalized for display)."""

    status: str = "idle"
    """Task status: 'idle', 'running', 'paused', 'completed', 'failed', 'cancelled'."""

    progress_pct: float = 0.0
    """Task completion percentage (0-100)."""

    area_completed_sq_m: float = 0.0
    """Area covered so far in square meters."""

    area_total_sq_m: float = 0.0
    """Total zone area in square meters."""

    elapsed_seconds: int = 0
    """Wall-clock seconds since task started."""

    battery_used_pct: float = 0.0
    """Battery percentage consumed by this task so far."""

    battery_start_pct: float = 0.0
    """Battery percentage when the task started."""

    coverage_path: List[Dict[str, float]] = field(default_factory=list)
    """GPS path points recorded during the task: [{'lat': ..., 'lng': ...}]."""

    fail_reason: Optional[str] = None
    """Reason for failure: 'obstacle', 'battery_low', 'stuck', 'connection_lost', 'estop'."""

    can_resume: bool = False
    """Whether the task can be resumed from its current position."""

    started_at_ms: Optional[int] = None
    """Unix ms when the task started."""

    parameters: Optional[Dict[str, Any]] = None
    """Task-specific parameters used for this execution."""

    def is_active(self) -> bool:
        """Check if a task is currently running or paused (resumable)."""
        return self.status in ("running", "paused")

    def reset(self) -> None:
        """Reset to idle state. Called after task completion or cancellation."""
        self.task_id = None
        self.task_type = None
        self.zone_id = None
        self.zone_name = None
        self.status = "idle"
        self.progress_pct = 0.0
        self.area_completed_sq_m = 0.0
        self.area_total_sq_m = 0.0
        self.elapsed_seconds = 0
        self.battery_used_pct = 0.0
        self.battery_start_pct = 0.0
        self.coverage_path.clear()
        self.fail_reason = None
        self.can_resume = False
        self.started_at_ms = None
        self.parameters = None

    def to_websocket_dict(self) -> Dict[str, Any]:
        """Serialize to dict for WebSocket task_update message payload."""
        return {
            "task_id": self.task_id,
            "task_type": self.task_type,
            "zone_id": self.zone_id,
            "zone_name": self.zone_name,
            "status": self.status,
            "progress_pct": round(self.progress_pct, 1),
            "area_completed_sq_m": round(self.area_completed_sq_m, 1),
            "area_total_sq_m": round(self.area_total_sq_m, 1),
            "elapsed_seconds": self.elapsed_seconds,
            "battery_used_pct": round(self.battery_used_pct, 1),
            "coverage_path": self.coverage_path[-100:],  # last 100 points
            "can_resume": self.can_resume,
            "fail_reason": self.fail_reason,
        }

    def to_firestore_history_dict(self) -> Dict[str, Any]:
        """Serialize to dict for Firestore task_history document.

        Called after task completion. Includes full execution metrics.
        """
        return {
            "taskType": self.task_type,
            "zoneId": self.zone_id,
            "zoneName": self.zone_name,
            "status": self.status,
            "startedAt": self.started_at_ms,
            "durationMinutes": self.elapsed_seconds / 60.0,
            "activeDurationMinutes": self.elapsed_seconds / 60.0,  # TODO: subtract pause time
            "areaCoveredSqM": round(self.area_completed_sq_m, 1),
            "areaTotalSqM": round(self.area_total_sq_m, 1),
            "coveragePct": round(self.progress_pct, 1),
            "batteryStartPct": round(self.battery_start_pct, 1),
            "batteryEndPct": round(self.battery_start_pct - self.battery_used_pct, 1),
            "batteryUsedPct": round(self.battery_used_pct, 1),
            "failureReason": self.fail_reason,
            "pathSummary": {
                "pointCount": len(self.coverage_path),
                "storageRef": None,  # Set by FirebaseClient after upload
            },
        }


@dataclass
class AlertEntry:
    """A single diagnostic alert or fault event.

    Alerts are generated by the robot when a fault condition is detected
    (motor overcurrent, battery issue, obstacle, etc.) and are sent to
    the app via all channels and persisted to Firestore.
    """

    alert_id: str = ""
    """Unique alert ID."""

    severity: str = "info"
    """Severity level: 'critical', 'warning', 'info'."""

    category: str = "system"
    """Alert category: 'motor', 'blade', 'battery', 'connection', 'gps', 'sensor', 'system', 'safety'."""

    code: str = ""
    """Machine-readable error code (e.g., 'MOTOR_FL_OVERCURRENT')."""

    title: str = ""
    """Human-readable short title."""

    message: str = ""
    """Human-readable detailed message."""

    component: str = ""
    """Affected component (e.g., 'motor_fl', 'battery_pack')."""

    is_active: bool = True
    """True until the fault condition is resolved."""

    created_at_ms: int = 0
    """Unix ms when the alert was created."""

    def __post_init__(self) -> None:
        if self.created_at_ms == 0:
            self.created_at_ms = int(time.time() * 1000)
        if not self.alert_id:
            import uuid as _uuid
            self.alert_id = str(_uuid.uuid4())

    def to_websocket_dict(self) -> Dict[str, Any]:
        """Serialize for WebSocket alert message payload."""
        return {
            "severity": self.severity,
            "category": self.category,
            "code": self.code,
            "title": self.title,
            "message": self.message,
            "component": self.component,
        }

    def to_firestore_dict(self) -> Dict[str, Any]:
        """Serialize for Firestore alerts subcollection document."""
        return {
            "severity": self.severity,
            "category": self.category,
            "code": self.code,
            "title": self.title,
            "message": self.message,
            "component": self.component,
            "isActive": self.is_active,
            "acknowledgedAt": None,
            "resolvedAt": None,
        }


@dataclass
class RobotState:
    """Central state manager for the robot server.

    This is the single source of truth for the robot's current state.
    All modules (BLE, WebSocket, Firebase, ROS2) read from and write to
    a shared instance of this class.

    Thread safety: The robot server uses asyncio with a single event loop.
    All state mutations happen on the event loop thread. No locking needed.
    """

    operational_state: OperationalState = OperationalState.IDLE
    """Current robot operational state."""

    pairing: PairingState = field(default_factory=PairingState)
    """BLE pairing state machine."""

    connection: ConnectionState = field(default_factory=ConnectionState)
    """Active connection tracking."""

    task: TaskState = field(default_factory=TaskState)
    """Active task state."""

    estop_active: bool = False
    """Whether E-Stop is currently engaged."""

    estop_source: Optional[str] = None
    """Source that triggered the E-Stop (e.g., 'app_ble', 'hardware_button')."""

    estop_triggered_at_ms: Optional[int] = None
    """Unix ms when E-Stop was triggered."""

    robot_name: str = "My ChoreBot"
    """User-assigned robot name."""

    attachment_type: str = "none"
    """Currently connected attachment type."""

    blade_on: bool = False
    """Whether the blade motor is currently running."""

    def set_estop(self, source: str) -> None:
        """Activate E-Stop from the given source.

        Args:
            source: One of 'app_ble', 'app_wifi', 'app_cloud', 'hardware_button', 'watchdog'
        """
        self.estop_active = True
        self.estop_source = source
        self.estop_triggered_at_ms = int(time.time() * 1000)
        self.operational_state = OperationalState.ESTOP
        self.blade_on = False

        # If a task was running, mark it as failed due to E-Stop
        if self.task.is_active():
            self.task.status = "failed"
            self.task.fail_reason = "estop"
            self.task.can_resume = True

    def clear_estop(self) -> bool:
        """Clear E-Stop after confirmation and self-diagnostics.

        Returns:
            True if E-Stop was successfully cleared.
            False if conditions are not met (should not happen if validation passed).
        """
        if not self.estop_active:
            return True

        self.estop_active = False
        self.estop_source = None
        self.estop_triggered_at_ms = None
        self.operational_state = OperationalState.IDLE
        return True

    def can_accept_command(self, command_type: str) -> bool:
        """Check if the robot can accept a command given its current state.

        E-Stop blocks ALL commands except 'estop_clear'.

        Args:
            command_type: The WebSocket message type or command name.

        Returns:
            True if the command is allowed in the current state.
        """
        if self.estop_active:
            return command_type in ("estop_clear", "estop")

        return True
